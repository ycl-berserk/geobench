"""The oracle harness: cross-check every operator against an independent implementation.

The harness owns the fixture format and the comparison logic. A kernel
operator is only allowed into the registry once its oracle battery passes, and
the coverage report is a CI gate: an operator without fixtures fails the build
(docs/spec.md section 5.3).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import sympy as sp
from sympy import Expr

from geobench.errors import StateError
from geobench.field import FIELD
from geobench.model import Figure, Node
from geobench.operators import OpContext
from geobench.registry import OperatorRegistry

FIXTURE_DIR = Path(__file__).parent / "fixtures"

# Each operator needs at least this many configurations, of which at least
# this many must be non-normal (a degenerate case, or an edge case that is
# unusual but still well defined). An operator that declares
# ``degenerate_when`` must additionally have degenerate cases.
MIN_CONFIGS = 20
MIN_NON_NORMAL = 3
MIN_DEGENERATE = 3


@dataclass
class Fixture:
    """One test configuration for an operator.

    ``points`` gives the exact coordinates of every free point the operator
    needs; ``args`` gives the node ids to pass.

    ``kind`` is one of:

    - ``normal``   -- an ordinary configuration;
    - ``edge``     -- an unusual but well-defined configuration (the operator
      must still return the right value);
    - ``degenerate`` -- the configuration is undefined and the operator must
      refuse.

    ``expect`` is ``value`` or ``error``. A ``degenerate`` fixture always
    expects an error; that correspondence is asserted by the test suite.
    """

    points: dict[str, tuple[str, str]]
    args: list[str]
    kind: str  # "normal" | "edge" | "degenerate"
    expect: str  # "value" | "error"
    note: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "points": {k: list(v) for k, v in self.points.items()},
            "args": list(self.args),
            "kind": self.kind,
            "expect": self.expect,
            "note": self.note,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Fixture:
        points = {
            str(k): (str(v[0]), str(v[1])) for k, v in dict(data.get("points", {})).items()
        }
        return cls(
            points=points,
            args=[str(a) for a in data["args"]],
            kind=str(data["kind"]),
            expect=str(data["expect"]),
            note=str(data.get("note", "")),
        )


@dataclass
class Mismatch:
    op_id: str
    fixture: int
    detail: str

    def __str__(self) -> str:
        return f"{self.op_id}[{self.fixture}]: {self.detail}"


def load_fixtures(op_id: str) -> list[Fixture]:
    path = FIXTURE_DIR / f"{op_id}.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return [Fixture.from_dict(item) for item in data["fixtures"]]


def save_fixtures(op_id: str, fixtures: list[Fixture]) -> None:
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    payload = {
        "op_id": op_id,
        "note": "Generated by scripts/gen_fixtures.py; see docs/spec.md 5.3.",
        "fixtures": [fixture.to_dict() for fixture in fixtures],
    }
    (FIXTURE_DIR / f"{op_id}.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def _build_figure(fixture: Fixture) -> Figure:
    """Build the minimal figure an operator needs to run.

    The free points carry exact coordinates, not symbols: the oracle
    comparison is a numerical-identity check on one configuration, and the
    identity-level check belongs to the judges.

    Arguments that are lines or circles are written ``line:A,B`` /
    ``circle:A,B,C`` in the fixture and are built here with sympy's own
    geometry primitives -- never with the kernel's operators -- so the
    operator under test is never compared against itself.
    """
    figure = Figure(id="fig_fixture")
    for node_id, (x, y) in fixture.points.items():
        figure.add_node(
            Node(
                id=node_id,
                kind="point",
                role="free",
                coords=(x, y),
                placement=(x, y),
            )
        )
    for index, spec in enumerate(fixture.args):
        if spec.startswith("line:"):
            ids = spec.split(":")[1].split(",")
            coefficients = _line_coefficients(figure, ids[0], ids[1])
            node_id = f"_l{index}"
            figure.add_node(Node(id=node_id, kind="line", role="free", op="line.free", args=ids))
            figure.nodes[node_id].cache["line"] = coefficients
            fixture.args[index] = node_id
        elif spec.startswith("segment:"):
            ids = spec.split(":")[1].split(",")
            first = _sympy_point(figure, ids[0])
            second = _sympy_point(figure, ids[1])
            node_id = f"_s{index}"
            figure.add_node(
                Node(id=node_id, kind="segment", role="free", op="segment.free", args=ids)
            )
            figure.nodes[node_id].cache["segment"] = (
                first.x,
                first.y,
                second.x,
                second.y,
            )
            fixture.args[index] = node_id
        elif spec.startswith("polygon:"):
            ids = spec.split(":")[1].split(",")
            node_id = f"_p{index}"
            vertices: list[Any] = []
            for point_id in ids:
                point = _sympy_point(figure, point_id)
                vertices.extend((point.x, point.y))
            figure.add_node(
                Node(id=node_id, kind="polygon", role="free", op="polygon.free", args=ids)
            )
            figure.nodes[node_id].cache["polygon"] = tuple(vertices)
            fixture.args[index] = node_id
        elif spec.startswith("circle:"):
            ids = spec.split(":")[1].split(",")
            node_id = f"_c{index}"
            if len(ids) == 2:
                # A circle with a centre and a squared radius.
                centre = _sympy_point(figure, ids[0])
                r2 = sp.sympify(ids[1])
                if r2 == 0:
                    # sympy has no circle of no radius; the centre and
                    # the radius are all that is needed.
                    figure.add_node(
                        Node(id=node_id, kind="circle", role="free", op="circle.free", args=ids)
                    )
                    figure.nodes[node_id].cache["circle"] = (centre.x, centre.y, r2)
                    fixture.args[index] = node_id
                    continue
                circle = sp.Circle(centre, sp.sqrt(r2))
                figure.add_node(
                    Node(id=node_id, kind="circle", role="free", op="circle.free", args=ids)
                )
            else:
                points = [_sympy_point(figure, node_id) for node_id in ids]
                circle = sp.Circle(*points)
                figure.add_node(
                    Node(id=node_id, kind="circle", role="free", op="circle.through", args=ids)
                )
            figure.nodes[node_id].cache["circle"] = (
                circle.center.x,
                circle.center.y,
                circle.radius ** 2,
            )
            fixture.args[index] = node_id
    return figure


def _sympy_point(figure: Figure, node_id: str) -> sp.Point:
    node = figure.node(node_id)
    if node.coords is None:
        raise StateError(f"point {node_id!r} has no coordinates")
    return sp.Point(FIELD.coerce(node.coords[0]), FIELD.coerce(node.coords[1]))


def _line_coefficients(figure: Figure, first: str, second: str) -> tuple[Expr, Expr, Expr]:
    """Coefficients of the line through two points.

    Uses sympy's own Line where it accepts the pair, and falls back to the
    determinant form when the two points coincide -- sympy refuses to build a
    line through a single point, but the degenerate case is exactly what the
    battery needs to exercise.
    """
    p1 = _sympy_point(figure, first)
    p2 = _sympy_point(figure, second)
    try:
        coefficients = sp.Line(p1, p2).coefficients
        return (coefficients[0], coefficients[1], coefficients[2])
    except ValueError:
        x1, y1 = p1.x, p1.y
        x2, y2 = p2.x, p2.y
        return (y1 - y2, x2 - x1, x1 * y2 - x2 * y1)


def canonical_line(a: Expr, b: Expr, c: Expr) -> tuple[Expr, Expr, Expr]:
    """Normalise an implicit line equation so two lines can be compared.

    ``a*x + b*y + c = 0`` is only defined up to a non-zero factor, so the
    kernel and the oracle will generally disagree on the factor while
    describing the same line. Dividing by the norm and fixing the sign
    removes that ambiguity exactly.
    """
    norm = sp.sqrt(a * a + b * b)
    if norm == 0:
        return (a, b, c)
    na, nb, nc = a / norm, b / norm, c / norm
    if na < 0 or (na == 0 and nb < 0):
        na, nb, nc = -na, -nb, -nc
    return (na, nb, nc)


def _expressions_equal(left: Expr, right: Expr) -> bool:
    """Are two exact expressions the same number?

    ``simplify_to_zero`` is the fast path, but it only handles polynomials over
    rationals. Two expressions involving radicals can be equal without their
    difference reducing to zero by that route -- the incenter is the classic
    case -- so a radical-aware reduction is tried as well.

    Before either of those, there is a much cheaper question: the fixtures
    use *exact integer* coordinates, so both sides are concrete algebraic
    numbers. If they agree to twelve digits they are the same number, and
    saying so takes microseconds instead of minutes. The exact reduction
    still runs when the numbers differ, so a genuine mismatch is still
    caught.
    """
    if FIELD.simplify_to_zero(left - right):
        return True
    if not left.free_symbols and not right.free_symbols:
        try:
            lhs = complex(sp.N(left, 30))
            rhs = complex(sp.N(right, 30))
        except (TypeError, ValueError):  # pragma: no cover - defensive
            lhs = rhs = None
        if lhs is not None and rhs is not None:
            scale = max(1.0, abs(lhs), abs(rhs))
            if abs(lhs - rhs) <= 1e-12 * scale:
                return True
    difference = left - right
    if sp.count_ops(difference) > 2000:
        return False
    try:
        return bool(sp.radsimp(sp.simplify(difference)) == 0)
    except Exception:  # pragma: no cover - sympy internal failure
        return False


# Operators whose result is one of several roots: the kernel picks one by a
# convention, so the oracle returns the whole set and the harness checks
# membership rather than position.
SET_COMPARISON = {"point.intersect_line_circle", "point.intersect_circles"}


def _compare_set(kernel_value: Any, oracle_value: Any) -> str | None:
    """The kernel's point must be one of the oracle's points."""
    kernel_parts = list(kernel_value) if isinstance(kernel_value, tuple) else [kernel_value]
    if len(kernel_parts) != 2:
        return f"expected a point, got {len(kernel_parts)} components"
    kx, ky = FIELD.coerce(kernel_parts[0]), FIELD.coerce(kernel_parts[1])
    for ox, oy in oracle_value:
        if _expressions_equal(kx, FIELD.coerce(ox)) and _expressions_equal(ky, FIELD.coerce(oy)):
            return None
    return (
        f"the kernel's point is not one of the oracle's intersections: "
        f"kernel=({sp.sstr(kx)}, {sp.sstr(ky)})"
    )


_PAYLOAD_ORDER = (
    "coords",
    "line",
    "segment",
    "circle",
    "polygon",
    "arc",
    "sector",
    "value",
)


def _payload_of(kernel_result: dict[str, Any]) -> Any:
    """The value the kernel computed, whatever shape it has.

    Each operator carries its result under a key named after the kind
    of object it produces, so the comparison asks for the one that is
    there.
    """
    for key in _PAYLOAD_ORDER:
        if key in kernel_result:
            return kernel_result[key]
    return None


def _compare(kind: str, kernel_value: Any, oracle_value: Any) -> str | None:
    """Return None when the two agree, otherwise a description of the difference."""
    kernel_parts = list(kernel_value) if isinstance(kernel_value, tuple) else [kernel_value]
    oracle_parts = list(oracle_value) if isinstance(oracle_value, tuple) else [oracle_value]
    if len(kernel_parts) != len(oracle_parts):
        return f"arity differs: kernel {len(kernel_parts)} vs oracle {len(oracle_parts)}"
    if kind == "line":
        left = canonical_line(*(FIELD.coerce(part) for part in kernel_parts))
        right = canonical_line(*(FIELD.coerce(part) for part in oracle_parts))
        for index, (lhs, rhs) in enumerate(zip(left, right, strict=True)):
            if _expressions_equal(lhs, rhs):
                continue
            return (
                f"coefficient {index} differs: kernel={sp.sstr(lhs)} oracle={sp.sstr(rhs)}"
            )
        return None
    for index, (left, right) in enumerate(zip(kernel_parts, oracle_parts, strict=True)):
        left_expr = FIELD.coerce(left)
        right_expr = FIELD.coerce(right)
        if _expressions_equal(left_expr, right_expr):
            continue
        return (
            f"component {index} differs: kernel={sp.sstr(left_expr)} "
            f"oracle={sp.sstr(right_expr)}"
        )
    return None


def check_operator(
    op_id: str,
    registry: OperatorRegistry,
    oracle_impl: Any,
) -> list[Mismatch]:
    """Run an operator's whole fixture battery against its oracle."""
    from oracles import ORACLES

    impl = registry.implementation(op_id)
    if impl is None:
        return [Mismatch(op_id, -1, "operator has no implementation")]
    oracle = ORACLES.get(op_id, oracle_impl)
    if oracle is None:
        return [Mismatch(op_id, -1, "operator has no oracle")]

    mismatches: list[Mismatch] = []
    for index, fixture in enumerate(load_fixtures(op_id)):
        figure = _build_figure(fixture)
        ctx = OpContext(figure)
        try:
            kernel_result = impl(ctx, list(fixture.args))
        except StateError as exc:
            if fixture.expect == "error":
                continue
            mismatches.append(Mismatch(op_id, index, f"kernel raised {exc}, expected a value"))
            continue
        if fixture.expect == "error":
            mismatches.append(
                Mismatch(op_id, index, "kernel returned a value, expected a degenerate error")
            )
            continue
        try:
            oracle_result = oracle(ctx, list(fixture.args))
        except Exception as exc:  # the oracle may refuse what the kernel allows
            mismatches.append(Mismatch(op_id, index, f"oracle failed: {exc}"))
            continue
        kernel_value = _payload_of(kernel_result)
        kind = str(kernel_result.get("kind", "point"))
        if op_id in SET_COMPARISON:
            detail = _compare_set(kernel_value, oracle_result)
        else:
            detail = _compare(kind, kernel_value, oracle_result)
        if detail is not None:
            mismatches.append(Mismatch(op_id, index, detail))
    return mismatches


def coverage_report(registry: OperatorRegistry) -> str:
    """A markdown table of every operator's fixture coverage."""
    rows = ["| operator | fixtures | degenerate | has oracle |", "|---|---|---|---|"]
    from oracles import ORACLES

    for op_id in registry.ids():
        fixtures = load_fixtures(op_id)
        degenerate = sum(1 for f in fixtures if f.kind == "degenerate")
        rows.append(
            f"| `{op_id}` | {len(fixtures)} | {degenerate} | {'yes' if op_id in ORACLES else 'NO'} |"
        )
    return "\n".join(rows)


def uncovered_operators(registry: OperatorRegistry) -> list[str]:
    """Operators that are not yet covered by a passing fixture battery.

    An operator is covered when it has enough configurations, enough
    non-normal ones, an oracle, and -- if it declares ``degenerate_when`` --
    enough genuinely degenerate cases.
    """
    from oracles import ORACLES

    missing: list[str] = []
    for op_id in registry.ids():
        if op_id == "point.free":
            continue
        fixtures = load_fixtures(op_id)
        degenerate = sum(1 for f in fixtures if f.kind == "degenerate")
        non_normal = sum(1 for f in fixtures if f.kind != "normal")
        spec = registry.lookup(op_id)
        if len(fixtures) < MIN_CONFIGS or non_normal < MIN_NON_NORMAL:
            missing.append(op_id)
        elif spec.degenerate_when and degenerate < MIN_DEGENERATE:
            missing.append(op_id)
        elif op_id not in ORACLES:
            missing.append(op_id)
    return missing
